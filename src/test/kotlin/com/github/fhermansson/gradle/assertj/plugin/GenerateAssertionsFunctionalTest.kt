    @Test
    fun `assertions are generated for kotlin classes and usable in kotlin tests`() {
        /*
         * Kotlin main sources, Kotlin test sources: the whole chain must work —
         * generation reads compiled Kotlin classes from the runtime classpath, and the
         * generated Java sources must join the Kotlin test compile.
         */
        projectDir.resolve("settings.gradle").writeText("rootProject.name = 'sample'\n")
        projectDir.resolve("build.gradle").writeText(
            """
            plugins {
                id 'org.jetbrains.kotlin.jvm' version '2.0.21'
                id 'com.github.fhermansson.assertj-generator'
            }

            repositories { mavenCentral() }
            dependencies {
                testImplementation 'org.assertj:assertj-core:3.27.7'
                testImplementation 'org.junit.jupiter:junit-jupiter:5.14.4'
                testRuntimeOnly 'org.junit.platform:junit-platform-launcher'
                testCompileOnly 'jakarta.annotation:jakarta.annotation-api:2.1.1'
            }

            tasks.withType(Test).configureEach { useJUnitPlatform() }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
            }
            """.trimIndent(),
        )
        projectDir.resolve("src/main/kotlin/com/example/model/KotlinItem.kt").apply {
            parentFile.mkdirs()
            writeText(
                """
                package com.example.model

                data class KotlinItem(val name: String)

                enum class KotlinStatus { ACTIVE, INACTIVE }
                """.trimIndent(),
            )
        }
        projectDir.resolve("src/test/kotlin/com/example/KotlinItemTest.kt").apply {
            parentFile.mkdirs()
            writeText(
                """
                package com.example

                import com.example.model.KotlinItem
                import com.example.model.KotlinStatus
                import org.junit.jupiter.api.Test
                import org.assertj.core.api.Assertions.assertThatThrownBy
                import com.example.model.Assertions.assertThat

                class KotlinItemTest {
                    @Test
                    fun generatedAssertionVerifiesKotlinProperty() {
                        val item = KotlinItem("abc")
                        assertThat(item).hasName("abc")
                        assertThat(item.name).isEqualTo("abc")
                    }

                    @Test
                    fun kotlinEnumAssertionWorks() {
                        /*
                         * Kotlin enums compiled with 1.9+ carry a kotlin.enums.EnumEntries
                         * internal EnumEntries field; class inspection must resolve it through the
                         * task's isolated class loader (regression guard).
                         */
                        assertThat(KotlinStatus.ACTIVE).isEqualTo(KotlinStatus.ACTIVE)
                    }

                    @Test
                    fun generatedAssertionFailsWithDescriptiveMessage() {
                        val item = KotlinItem("abc")
                        assertThatThrownBy { assertThat(item).hasName("foo") }
                            .isInstanceOf(AssertionError::class.java)
                            .hasMessageContaining("Expecting name of")
                            .hasMessageContaining("to be:")
                            .hasMessageContaining("<foo>")
                            .hasMessageContaining("but was:")
                            .hasMessageContaining("<abc>")
                    }
                }
                """.trimIndent(),
            )
        }

        val test =
            GradleRunner
                .create()
                .withProjectDir(projectDir)
                .withPluginClasspath()
                .withArguments("test", "--warning-mode=all")
                .build()

        assertThat(test.task(":generateAssertions")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
        assertThat(test.task(":compileTestKotlin")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
        assertThat(test.task(":test")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
    }
