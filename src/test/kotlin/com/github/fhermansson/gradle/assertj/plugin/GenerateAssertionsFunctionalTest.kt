    @Test
    fun `generateForNonPublicFields includes non-public field assertions`() {
        fun buildScript(allFields: Boolean) =
            """
            plugins {
                id 'java'
                id 'com.github.fhermansson.assertj-generator'
            }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
                generateForNonPublicFields = $allFields
            }

            repositories { mavenCentral() }
            """.trimIndent()

        writeProject(buildScript(allFields = false))
        projectDir.resolve("src/main/java/com/example/model/Plain.java").apply {
            parentFile.mkdirs()
            writeText(
                """
                package com.example.model;

                public class Plain {
                    String hidden; // package-private field, no accessor
                }
                """.trimIndent(),
            )
        }

        fun run() = GradleRunner
            .create()
            .withProjectDir(projectDir)
            .withPluginClasspath()
            .withArguments("generateAssertions", "--rerun-tasks")
            .build()

        // Default: fields without public accessors get no assertions.
        run()
        val defaultGenerated =
            projectDir
                .resolve("build/generated/sources/assertj/test/com/example/model/PlainAssert.java")
                .readText()
        assertThat(defaultGenerated).doesNotContain("hasHidden")

        // With generateForNonPublicFields: the package-private field is asserted too.
        writeProject(buildScript(allFields = true))
        val build = run()

        assertThat(build.task(":generateAssertions")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
        val generated =
            projectDir
                .resolve("build/generated/sources/assertj/test/com/example/model/PlainAssert.java")
                .readText()
        assertThat(generated).contains("hasHidden")
    }

