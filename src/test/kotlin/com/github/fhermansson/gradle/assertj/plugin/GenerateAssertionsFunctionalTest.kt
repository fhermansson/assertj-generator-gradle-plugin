    @Test
    fun `entryPointInherits false generates standalone entry point`() {
        /*
         * entryPointInherits=true (default) makes the entry point extend
         * org.assertj.core.api.Assertions; with false, the class must be standalone.
         */
        fun buildScript(inherits: Boolean) =
            """
            plugins {
                id 'java'
                id 'com.github.fhermansson.assertj-generator'
            }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
                entryPointInherits = $inherits
            }

            repositories { mavenCentral() }
            """.trimIndent()

        fun run() = GradleRunner
            .create()
            .withProjectDir(projectDir)
            .withPluginClasspath()
            .withArguments("generateAssertions", "--rerun-tasks")
            .build()

        fun entryPoint() = projectDir
            .resolve("build/generated/sources/assertj/test/com/example/model/Assertions.java")
            .readText()

        writeProject(buildScript(inherits = true))
        run()
        assertThat(entryPoint()).contains("extends org.assertj.core.api.Assertions")

        writeProject(buildScript(inherits = false))
        run()
        assertThat(entryPoint()).doesNotContain("extends org.assertj.core.api.Assertions")
    }

    @Test
    fun `cleanOutputDir false keeps stale files and true removes them`() {
        fun buildScript(clean: Boolean) =
            """
            plugins {
                id 'java'
                id 'com.github.fhermansson.assertj-generator'
            }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
                cleanOutputDir = $clean
            }

            repositories { mavenCentral() }
            """.trimIndent()

        val staleFile =
            projectDir.resolve("build/generated/sources/assertj/test/com/example/model/Stale.java")

        fun run() = GradleRunner
            .create()
            .withProjectDir(projectDir)
            .withPluginClasspath()
            .withArguments("generateAssertions", "--rerun-tasks")
            .build()

        writeProject(buildScript(clean = false))
        run()
        staleFile.parentFile.mkdirs()
        staleFile.writeText("// stale")
        run()
        assertThat(staleFile).exists()

        writeProject(buildScript(clean = true))
        run()
        assertThat(staleFile).doesNotExist()
    }

