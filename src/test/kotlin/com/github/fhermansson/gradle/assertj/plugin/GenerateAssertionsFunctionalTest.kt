package com.github.fhermansson.gradle.assertj.plugin

import org.assertj.core.api.Assertions.assertThat
import org.gradle.testkit.runner.GradleRunner
import org.gradle.testkit.runner.TaskOutcome
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File

class GenerateAssertionsFunctionalTest {
    @TempDir
    lateinit var projectDir: File

    private fun writeProject(
        buildScript: String,
        kotlinDsl: Boolean = false,
    ) {
        if (kotlinDsl) {
            projectDir.resolve("settings.gradle.kts").writeText("rootProject.name = \"sample\"\n")
        } else {
            projectDir.resolve("settings.gradle").writeText("rootProject.name = 'sample'\n")
        }
        projectDir
            .resolve(
                if (kotlinDsl) "build.gradle.kts" else "build.gradle",
            ).writeText(buildScript)
        projectDir.resolve("src/main/java/com/example/model/Item.java").apply {
            parentFile.mkdirs()
            writeText(
                """
                package com.example.model;

                public class Item {
                    private String name;
                    public String getName() { return name; }
                    public void setName(String name) { this.name = name; }
                }
                """.trimIndent(),
            )
        }
    }

    @Test
    fun `generateAssertions produces assertion class and entry point and compiles into tests`() {
        writeProject(
            """
            plugins {
                id 'java'
                id 'com.github.fhermansson.assertj-generator'
            }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
            }

            repositories { mavenCentral() }
            dependencies {
                testImplementation 'org.assertj:assertj-core:3.27.7'
                // Generated sources carry @jakarta.annotation.Generated by default
                testCompileOnly 'jakarta.annotation:jakarta.annotation-api:2.1.1'
            }
            """.trimIndent(),
        )

        val build =
            GradleRunner
                .create()
                .withProjectDir(projectDir)
                .withPluginClasspath()
                .withArguments("compileTestJava", "--warning-mode=all")
                .build()

        assertThat(build.task(":generateAssertions")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
        assertThat(build.task(":compileTestJava")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)

        val generatedDir = projectDir.resolve("build/generated/sources/assertj/test")
        val assertionClass = generatedDir.resolve("com/example/model/Assertions.java")
        val entryPoint = generatedDir.resolve("com/example/model/ItemAssert.java")
        assertThat(assertionClass).describedAs("Assertions entry point not generated").exists()
        assertThat(entryPoint).describedAs("ItemAssert not generated").exists()
        assertThat(entryPoint.readText()).contains("class ItemAssert")
    }

    @Test
    fun `custom GenerateAssertions task inherits extension defaults`() {
        writeProject(
            """
            plugins {
                id 'java'
                id 'com.github.fhermansson.assertj-generator'
            }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
                entryPointPackage = 'com.example.assertj'
            }

            repositories { mavenCentral() }
            dependencies { testImplementation 'org.assertj:assertj-core:3.27.7' }

            import com.github.fhermansson.gradle.assertj.plugin.GenerateAssertions

            tasks.register('generateOtherAssertions', GenerateAssertions) {
                classOrPackageNames = ['com.example.model']
                outputDir = layout.buildDirectory.dir('other-generated-java')
                testSourceSet = sourceSets.test
            }
            """.trimIndent(),
        )

        val build =
            GradleRunner
                .create()
                .withProjectDir(projectDir)
                .withPluginClasspath()
                .withArguments("generateOtherAssertions", "--warning-mode=all")
                .build()

        assertThat(build.task(":generateOtherAssertions")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
        val outDir = projectDir.resolve("build/other-generated-java")
        assertThat(outDir.resolve("com/example/model/ItemAssert.java")).exists()
        assertThat(outDir.resolve("com/example/assertj/Assertions.java")).exists()
    }

    @Test
    fun `build is configuration cache compatible`() {
        writeProject(
            """
            plugins {
                java
                id("com.github.fhermansson.assertj-generator")
            }

            assertjGenerator {
                classOrPackageNames = listOf("com.example.model")
            }

            repositories { mavenCentral() }
            dependencies { testImplementation("org.assertj:assertj-core:3.27.7") }
            """.trimIndent(),
            kotlinDsl = true,
        )

        /*
         * First run stores the configuration; second run must reuse it (UP-TO-DATE task
         * outcomes prove the cached configuration was used, not rebuilt).
         */
        GradleRunner
            .create()
            .withProjectDir(projectDir)
            .withPluginClasspath()
            .withArguments("generateAssertions", "--configuration-cache", "--warning-mode=all")
            .build()
        val reuse =
            GradleRunner
                .create()
                .withProjectDir(projectDir)
                .withPluginClasspath()
                .withArguments("generateAssertions", "--configuration-cache", "--warning-mode=all")
                .build()

        assertThat(reuse.output).contains("Reusing configuration cache.")
        assertThat(reuse.task(":generateAssertions")!!.outcome).isEqualTo(TaskOutcome.UP_TO_DATE)
    }

    @Test
    fun `generateAssertions is build-cacheable`() {
        writeProject(
            """
            plugins {
                id 'java'
                id 'com.github.fhermansson.assertj-generator'
            }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
            }

            repositories { mavenCentral() }
            """.trimIndent(),
        )

        GradleRunner
            .create()
            .withProjectDir(projectDir)
            .withPluginClasspath()
            .withArguments("generateAssertions", "--build-cache")
            .build()
        /*
         * Removing the outputs and rebuilding must not re-run the generator:
         * the cache entry is restored instead (FROM-CACHE).
         */
        projectDir.resolve("build/generated").deleteRecursively()
        val fromCache =
            GradleRunner
                .create()
                .withProjectDir(projectDir)
                .withPluginClasspath()
                .withArguments("generateAssertions", "--build-cache")
                .build()

        assertThat(fromCache.task(":generateAssertions")!!.outcome).isEqualTo(TaskOutcome.FROM_CACHE)
        val generatedDir = projectDir.resolve("build/generated/sources/assertj/test")
        assertThat(generatedDir.resolve("com/example/model/ItemAssert.java")).exists()
    }

    @Test
    fun `generated assertions are usable in a consumer unit test`() {
        writeProject(
            """
            plugins {
                id 'java'
                id 'com.github.fhermansson.assertj-generator'
            }

            assertjGenerator {
                classOrPackageNames = ['com.example.model']
            }

            repositories { mavenCentral() }
            dependencies {
                testImplementation 'org.assertj:assertj-core:3.27.7'
                testImplementation 'org.junit.jupiter:junit-jupiter:5.14.4'
                testRuntimeOnly 'org.junit.platform:junit-platform-launcher'
                // Generated sources carry @jakarta.annotation.Generated by default
                testCompileOnly 'jakarta.annotation:jakarta.annotation-api:2.1.1'
            }

            tasks.withType(Test).configureEach { useJUnitPlatform() }
            """.trimIndent(),
        )
        projectDir.resolve("src/test/java/com/example/ItemTest.java").apply {
            parentFile.mkdirs()
            writeText(
                """
                package com.example;

                import com.example.model.Item;
                import org.junit.jupiter.api.Test;

                import static com.example.model.Assertions.assertThat;

                class ItemTest {
                    @Test
                    void generatedAssertionVerifiesProperty() {
                        Item item = new Item();
                        item.setName("abc");
                        assertThat(item).hasName("abc");
                    }
                }
                """.trimIndent(),
            )
        }

        val test =
            GradleRunner
                .create()
                .withProjectDir(projectDir)
                .withPluginClasspath()
                .withArguments("test", "--warning-mode=all")
                .build()

        assertThat(test.task(":generateAssertions")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
        assertThat(test.task(":compileTestJava")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)
        assertThat(test.task(":test")!!.outcome).isEqualTo(TaskOutcome.SUCCESS)

        val generated =
            projectDir
                .resolve("build/generated/sources/assertj/test/com/example/model/ItemAssert.java")
                .readText()
        assertThat(generated).contains("@jakarta.annotation.Generated")
    }

